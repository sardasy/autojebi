import {expect, test} from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
import {testPdf} from "./fixtures/attachmentOnly";
import type {Workspace} from "../src/lib/workspace";

test("TEST ONLY: explicit UI JEV request persists once and becomes historical after source edit", async ({page, request}, testInfo) => {
  test.skip(process.env.E2E_JEV_LIVE !== "true", "explicit synthetic JEV call only");
  test.setTimeout(180_000);
  const api = process.env.E2E_API_BASE || "http://127.0.0.1:8002";
  const noticeNo = `E2E-JEV-${Date.now()}`;
  const prefix = `/v2/notices/${noticeNo}`;
  const output = path.resolve("../data/workspace/jev-loop", noticeNo);
  await fs.mkdir(output, {recursive: true});
  const state = async (): Promise<Workspace> => (await request.get(`${api}${prefix}/workspace`)).json();
  const classification = async () => (await request.get(`${api}${prefix}/classification`)).json();
  const sourceText = "TEST ONLY fictional procurement of a real-time HIL simulator for HVDC converter controller verification.";
  await page.goto("/workspace");
  await page.getByText("공고 수동 등록", {exact: true}).click();
  await page.getByLabel("공고번호", {exact: true}).fill(noticeNo);
  await page.getByLabel("공고명", {exact: true}).fill("[TEST ONLY] HVDC controller HIL simulator");
  await page.getByLabel("공고 기관", {exact: true}).fill("Example Research Institute");
  await page.getByLabel("입찰 마감일시 (한국시간)", {exact: true}).fill(`${new Date(Date.now() + 30 * 86400000).toISOString().slice(0, 10)}T14:00`);
  await page.getByRole("button", {name: "등록", exact: true}).click();
  await expect(page.getByText("공고 등록 완료", {exact: true})).toBeVisible();
  await page.getByLabel("공고 검색", {exact: true}).fill(noticeNo);
  await page.getByRole("button", {name: "공고 검색 실행", exact: true}).click();
  await page.locator(`a[href="/workspace/${noticeNo}"]`).click();
  await page.getByRole("button", {name: "검토 시작", exact: true}).click();
  await page.getByRole("region", {name: "지금 할 작업"}).getByRole("button", {name: "공고 원문 등록"}).click();
  await page.getByLabel("파일", {exact: true}).setInputFiles({name: "test-only-jev.pdf", mimeType: "application/pdf", buffer: testPdf([sourceText])});
  await page.getByRole("button", {name: "등록", exact: true}).click();
  await expect(page.getByRole("status", {name: "실행 결과"})).toContainText("파일 등록 완료");
  await page.getByRole("region", {name: "지금 할 작업"}).getByRole("button", {name: "원문 본문 추출"}).click();
  await expect.poll(async () => (await state()).jobs.find(job => job.kind === "extract")?.status).toBe("succeeded");
  await page.getByRole("region", {name: "지금 할 작업"}).getByRole("button", {name: "추출한 본문 반영"}).click();
  await expect(page.getByRole("status", {name: "실행 결과"})).toContainText("본문 반영 완료");
  const before = await state();
  const panel = page.getByRole("region", {name: "JEV 공고 분류"});
  await expect(panel.getByRole("button", {name: "JEV 분류 실행", exact: true})).toBeEnabled();
  const context = await classification();
  expect(context.policy_version).toBe("autojebi-day1-v1");
  expect(context.history).toHaveLength(0);
  await panel.getByRole("button", {name: "JEV 분류 실행", exact: true}).click();
  await expect.poll(async () => (await state()).jobs.find(job => job.kind === "jev")?.status, {timeout: 60_000}).toBe("succeeded");
  await expect(panel.getByText("HIL", {exact: true})).toBeVisible();
  await expect(panel.getByText("HVDC", {exact: true})).toBeVisible();
  const evaluated = await classification();
  const job = evaluated.history[0];
  expect(job.result.decision_id).toBeTruthy();
  const after = await state();
  expect(after.version).toBe(before.version);
  expect(after.decision).toBe(before.decision);
  expect(after.ready).toBe(false);
  expect(after.reviews).toEqual(before.reviews);
  await panel.getByRole("button", {name: "JEV 결과 다시 확인"}).click();
  await expect(page.getByRole("status", {name: "실행 결과"})).toContainText("JEV 분류 · 완료");
  expect((await classification()).history.map((row: {id: string}) => row.id)).toEqual([job.id]);
  await page.reload();
  await expect(panel.getByText(`저장 기록: ${job.result.decision_id}`, {exact: true})).toBeVisible();
  await page.screenshot({path: path.join(output, "classified.png"), fullPage: true});
  const sourceDetails = page.locator("#source-details");
  await page.getByText("검토 의견·상태 관리", {exact: true}).click();
  await page.getByLabel("검토 의견", {exact: true}).fill("TEST ONLY 원문 변경 후 이전 분류 구분 검증");
  if (await sourceDetails.getAttribute("open") === null) await sourceDetails.locator(":scope > summary").click();
  await page.getByText("원문·증빙 파일 관리 · 1개", {exact: true}).click();
  const textInput = page.getByLabel("test-only-jev.pdf 본문", {exact: true});
  const ancestors = await textInput.locator("xpath=ancestor::details[not(@open)]").all();
  for (const details of ancestors.reverse()) await details.locator(":scope > summary").click();
  await textInput.fill(`${sourceText}\nTEST ONLY: revised original for a different application.`);
  await page.getByRole("button", {name: "확인된 본문 저장", exact: true}).click();
  await expect(panel.getByText(/현재 원문·정책의 분류 결과가 없습니다/)).toBeVisible();
  const changed = await classification();
  expect(changed.current_job_id).toBeNull();
  expect(changed.history).toHaveLength(1);
  await page.screenshot({path: path.join(output, "historical.png"), fullPage: true});
  const report = {notice_no: noticeNo, job_id: job.id, decision_id: job.result.decision_id,
    evaluation: job.result.evaluation, classified_version: after.version,
    after_edit_version: (await state()).version, current_job_after_edit: changed.current_job_id,
    job_count: changed.history.length, ready: (await state()).ready};
  const reportPath = path.join(output, "result.json");
  await fs.writeFile(reportPath, JSON.stringify(report, null, 2));
  await testInfo.attach("jev-integration", {path: reportPath, contentType: "application/json"});
});
