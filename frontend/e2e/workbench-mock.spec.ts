import { expect, test } from "@playwright/test";

test.skip(process.env.E2E_MOCK !== "true", "Requires isolated workbench_mock_app on 8002");

test("workbench tabs, counts, warning review, failed approval, mobile and focus", async ({ page, request }) => {
  expect((await request.post(`${process.env.E2E_API_BASE}/__test__/reset`)).ok()).toBe(true);
  await page.goto("/notices?q=UX-MOCK");
  await expect(page.getByRole("heading", { name: "공고 작업대" })).toBeVisible();
  await expect(page.getByText("규격 후보 2개 · 요구값 확인 1개")).toBeVisible();
  await page.getByRole("link", { name: "모의 공고 작업대 검증" }).click();
  await page.getByRole("tab", { name: "규격 대응", exact: true }).click();
  await expect(page.getByText("요구값 확인 1개 · 빈 후보 1개")).toBeVisible();
  await page.getByRole("button", { name: "HWP 작성", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "HWP 작성", exact: true });
  await expect(modal.getByLabel("회사명 *")).toHaveValue("MOCK");
  await modal.getByLabel("회사명 *").fill("WARNING");
  await modal.getByRole("checkbox", { name: "규격대응표", exact: true }).uncheck();
  await modal.getByRole("button", { name: "작성", exact: true }).click();
  await expect(modal.getByText(/남은 placeholder 1개: address/)).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "HWP 작성", exact: true })).toBeFocused();
  await page.getByRole("tab", { name: "생성/검토", exact: true }).click();
  await expect(page.getByRole("button", { name: "승인", exact: true })).toBeDisabled();
  await page.getByRole("textbox", { name: /검토 의견/ }).fill("모의 경고 확인. 실 제출 금지.");
  await page.getByRole("button", { name: "승인", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "HWP 검토 상태: 승인" })).toBeVisible();
  await page.reload();
  await expect(page.getByText(/Job #.*승인/)).toBeVisible();
  await page.getByRole("tab", { name: "규격 대응", exact: true }).click();
  await page.getByRole("button", { name: "HWP 작성", exact: true }).click();
  await expect(modal.getByLabel("회사명 *")).toHaveValue("MOCK");
  await modal.getByLabel("회사명 *").fill("FAIL");
  await modal.getByRole("checkbox", { name: "규격대응표", exact: true }).uncheck();
  await modal.getByRole("button", { name: "작성", exact: true }).click();
  await expect(modal.getByText(/HWP 작성 불가/)).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("link", { name: "검토함", exact: true }).click();
  await page.getByRole("combobox", { name: "생성 상태", exact: true }).selectOption("failed");
  await page.getByRole("button", { name: "조회" }).click();
  await expect(page.getByRole("button", { name: "승인", exact: true })).toBeDisabled();
  await expect(page.getByText(/생성 실패로 승인할 수 없습니다/)).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByRole("link", { name: "공고 검색", exact: true }).click();
  await page.getByRole("textbox", { name: "G2B 검색어" }).fill("키없음");
  await page.getByRole("button", { name: "G2B 라이브 검색" }).click();
  await expect(page.getByRole("status").filter({ hasText: /키가 설정/ })).toBeVisible();
});

test("upload, spec editing, Excel and normal HWP persist across tabs and reload", async ({ page, request }) => {
  await request.post(`${process.env.E2E_API_BASE}/__test__/reset`);
  await page.goto("/notices/UX-MOCK?tab=documents");
  await page.getByRole("button", { name: "사업자등록증 업로드", exact: true }).click();
  const upload = page.getByRole("dialog", { name: "서류 파일 업로드" });
  await expect(upload.getByRole("combobox")).toHaveValue("business_registration");
  await upload.getByLabel("파일 선택").setInputFiles({ name: "ux-proof.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.4\n% mock upload\n%%EOF") });
  await upload.getByRole("button", { name: "업로드", exact: true }).click();
  await expect(upload).not.toBeVisible();
  await expect(page.getByRole("link", { name: "ux-proof.pdf" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("link", { name: "ux-proof.pdf" })).toBeVisible();
  await page.getByRole("tab", { name: "규격 대응", exact: true }).click();
  await page.getByLabel("전압 0 제안값").fill("230V");
  await page.getByLabel("전압 0 제안값").press("Tab");
  await expect(page.getByRole("status").filter({ hasText: "전압 0 저장 완료" })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("전압 0 제안값")).toHaveValue("230V");
  await page.getByRole("button", { name: "HWP 작성", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "HWP 작성", exact: true });
  await expect(modal.getByLabel("회사명 *")).toHaveValue("MOCK");
  await modal.getByRole("checkbox", { name: "규격대응표", exact: true }).uncheck();
  await modal.getByRole("button", { name: "작성", exact: true }).click();
  await expect(modal.getByText(/남은 placeholder 0개/)).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("tab", { name: "생성/검토", exact: true }).click();
  await expect(page.getByRole("button", { name: "승인", exact: true })).toBeEnabled();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("link", { name: "파일 다운로드", exact: true }).click();
  expect(await (await downloadEvent).failure()).toBeNull();
  await page.getByRole("button", { name: "Excel 생성", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Excel 파일 생성 완료" })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  for (const url of ["/notices?q=UX-MOCK", "/notices/UX-MOCK?tab=spec", "/search", "/admin"]) {
    await page.goto(url);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), url).toBe(true);
  }
  await page.goto("/search");
  await page.getByRole("textbox", { name: "G2B 검색어" }).fill("변압기");
  await page.getByRole("button", { name: "G2B 라이브 검색" }).click();
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page).toHaveURL(/\/notices\/UX-SEARCH/);
  await expect(page.getByRole("heading", { name: "모의 검색 공고" })).toBeVisible();
  await page.getByRole("button", { name: "분석", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "분석 완료" })).toBeVisible();
  await page.getByRole("button", { name: "그레이드", exact: true }).click();
  const grade = page.getByRole("dialog", { name: "그레이드 실행" });
  await expect(grade.getByRole("checkbox")).not.toBeChecked();
  await grade.getByRole("button", { name: "실행", exact: true }).click();
  await expect(grade.getByRole("status").filter({ hasText: "그레이드 완료" })).toBeVisible();
});
